// npm run fonts: turn the bundled TTFs in client/fonts into the MSDF atlases
// uikit draws with, in client/public/fonts (served from the bridge's own
// origin, no CDN, no runtime generation). Also writes the list of glyphs each
// atlas really holds to client/src/instrument/glyphs.ts, so the instrument
// can swap or drop characters a font lacks instead of drawing uikit's solid
// "missing glyph" box. Run it again after changing a font or the charset.

import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'

const root = resolve(import.meta.dirname, '..')
const src = join(root, 'client/fonts')
const out = join(root, 'client/public/fonts')
const bin = join(root, 'node_modules/.bin/msdf-bmfont')

// Printable ASCII, Latin-1 letters and the punctuation agents actually write.
let charset = ''
for (let c = 32; c < 127; c++) charset += String.fromCharCode(c)
for (let c = 0xc0; c <= 0xff; c++) charset += String.fromCharCode(c)
charset += '’‘“”–—…•·×÷°±£€§©®™→←↑↓↔⇒✓✗≈≠≤≥¼½¾'

const FONTS = [
  { file: 'Inter-Regular.ttf', name: 'inter-400' },
  { file: 'Inter-SemiBold.ttf', name: 'inter-600' },
  { file: 'Rajdhani-SemiBold.ttf', name: 'rajdhani-600' },
  { file: 'Rajdhani-Bold.ttf', name: 'rajdhani-700' },
]

mkdirSync(out, { recursive: true })
const work = join(tmpdir(), `claudevr-fonts-${process.pid}`)
mkdirSync(work, { recursive: true })
const charsetFile = join(work, 'charset.txt')
writeFileSync(charsetFile, charset)

const glyphs = {}
for (const f of FONTS) {
  const ttf = join(work, `${f.name}.ttf`)
  copyFileSync(join(src, f.file), ttf)
  execFileSync(bin, ['-f', 'json', '-o', join(work, f.name), '-s', '48', '-r', '6', '-p', '2', '-m', '1024,1024', '--pot', '-i', charsetFile, ttf], { stdio: ['ignore', 'ignore', 'inherit'] })
  // The tool names the JSON after the font face; find it by the page name instead.
  const json = execFileSync('sh', ['-c', `ls "${work}"/*.json`]).toString().trim().split('\n').find(p => JSON.parse(readFileSync(p, 'utf8')).pages[0] === `${f.name}.png`)
  if (!json) throw new Error(`no atlas JSON for ${f.name}`)
  const info = JSON.parse(readFileSync(json, 'utf8'))
  if (info.pages.length !== 1) throw new Error(`${f.name}: ${info.pages.length} pages; uikit takes exactly one. Raise the texture size.`)
  // Glyph index 0 is the font's "not defined" box: the face lacks that character.
  const lacks = info.chars.filter(c => c.index === 0 && c.char !== ' ').map(c => c.char)
  info.chars = info.chars.filter(c => c.index !== 0 || c.char === ' ')
  if (lacks.length) console.log(`${f.name}: lacks ${lacks.join('')}`)
  writeFileSync(join(out, `${f.name}.json`), JSON.stringify(info))
  copyFileSync(join(work, `${f.name}.png`), join(out, `${f.name}.png`))
  rmSync(json)
  glyphs[f.name] = info.chars.map(c => c.char).join('')
  console.log(`${f.name}: ${info.chars.length} glyphs, ${info.common.scaleW}x${info.common.scaleH}`)
}
copyFileSync(join(src, 'Inter-OFL.txt'), join(out, 'Inter-OFL.txt'))
copyFileSync(join(src, 'Rajdhani-OFL.txt'), join(out, 'Rajdhani-OFL.txt'))
rmSync(work, { recursive: true, force: true })

const ts = `// Generated by scripts/make-fonts.mjs: the glyphs each MSDF atlas holds.
// Edit the script, not this file.

export const GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const
`
writeFileSync(join(root, 'client/src/instrument/glyphs.ts'), ts)
